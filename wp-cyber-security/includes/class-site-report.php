	/**
	 * @param array $counts   Store::counts().
	 * @param array $last     Last scan.
	 * @param int   $baseline Baseline time.
	 * @return string
	 */
	private function section_overview( array $counts, array $last, $baseline ) {
		global $wp_version;
		$rows = array(
			__( 'Site address', 'wp-cyber-security' )        => home_url(),
			__( 'WordPress address', 'wp-cyber-security' )   => site_url(),
			__( 'WordPress version', 'wp-cyber-security' )   => (string) $wp_version . ( is_multisite() ? ' (' . __( 'multisite', 'wp-cyber-security' ) . ')' : '' ),
			__( 'PHP version', 'wp-cyber-security' )         => PHP_VERSION,
			__( 'Plugin version', 'wp-cyber-security' )      => WPCYBERSEC_VERSION,
			__( 'Waiting for a decision', 'wp-cyber-security' ) => number_format_i18n( isset( $counts['pending'] ) ? (int) $counts['pending'] : 0 ),
			__( 'Open threats', 'wp-cyber-security' )        => number_format_i18n( isset( $counts['threats'] ) ? (int) $counts['threats'] : 0 ),
			__( 'Held in quarantine', 'wp-cyber-security' )  => number_format_i18n( isset( $counts['quarantined'] ) ? (int) $counts['quarantined'] : 0 ),
			__( 'Allowlist entries', 'wp-cyber-security' )   => $this->allowlist_summary(),
			__( 'Baseline recorded', 'wp-cyber-security' )   => $baseline ? $this->when( $baseline ) : __( 'Not yet', 'wp-cyber-security' ),
			__( 'Last scan', 'wp-cyber-security' )           => ! empty( $last['finished_at'] ) ? $this->when( (int) $last['finished_at'] ) : __( 'Never', 'wp-cyber-security' ),
		);
		return '<section><h2>' . $this->t( __( 'Overview', 'wp-cyber-security' ) ) . '</h2>' . $this->kv( $rows ) . '</section>';
	}

	/**
	 * @return string "123 (100 files, 20 plugins and themes, 3 database values)".
	 */
	private function allowlist_summary() {
		$allow = wpcybersec()->allowlist;
		$total = (int) $allow->count();
		$parts = array();
		foreach (
			array(
				/* translators: %s: number of entries */
				'hash'    => __( 'files: %s', 'wp-cyber-security' ),
				/* translators: %s: number of entries */
				'install' => __( 'plugins and themes: %s', 'wp-cyber-security' ),
				/* translators: %s: number of entries */
				'db'      => __( 'database values: %s', 'wp-cyber-security' ),
			) as $kind => $label
		) {
			$result = $allow->query(
				array(
					'kind'     => $kind,
					'per_page' => 1,
				)
			);
			$n = isset( $result['total'] ) ? (int) $result['total'] : 0;
			if ( $n ) {
				$parts[] = sprintf( $label, number_format_i18n( $n ) );
			}
		}
		return number_format_i18n( $total ) . ( $parts ? ' (' . implode( ', ', $parts ) . ')' : '' );
	}

	/**
	 * @param array $last     Last scan.
	 * @param int   $baseline Baseline time.
	 * @return string
	 */
	private function section_scan( array $last, $baseline ) {
		$html = '<section><h2>' . $this->t( __( 'Last scan', 'wp-cyber-security' ) ) . '</h2>';
		if ( empty( $last['finished_at'] ) ) {
			return $html . '<p>' . $this->t( __( 'No scan has finished yet.', 'wp-cyber-security' ) ) . '</p></section>';
		}
		$modes = array(
			'incremental' => __( 'Quick scan (new and changed files)', 'wp-cyber-security' ),
			'full'        => __( 'Full malware scan', 'wp-cyber-security' ),
			'baseline'    => __( 'Baseline (every file trusted, malware still reported)', 'wp-cyber-security' ),
		);
		$mode  = isset( $last['mode'] ) ? (string) $last['mode'] : '';
		$rows  = array(
			__( 'Kind', 'wp-cyber-security' )            => isset( $modes[ $mode ] ) ? $modes[ $mode ] : $mode,
			__( 'Result', 'wp-cyber-security' )          => isset( $last['state'] ) ? (string) $last['state'] : '',
			__( 'Started', 'wp-cyber-security' )         => ! empty( $last['started_at'] ) ? $this->when( (int) $last['started_at'] ) : '',
			__( 'Finished', 'wp-cyber-security' )        => $this->when( (int) $last['finished_at'] ),
			__( 'Malware signatures', 'wp-cyber-security' ) => ! empty( $last['malware'] ) ? __( 'Yes', 'wp-cyber-security' ) : __( 'No', 'wp-cyber-security' ),
			__( 'Files checked', 'wp-cyber-security' )   => number_format_i18n( isset( $last['files_done'] ) ? (int) $last['files_done'] : 0 ),
			__( 'New files', 'wp-cyber-security' )       => number_format_i18n( isset( $last['new'] ) ? (int) $last['new'] : 0 ),
			__( 'Modified files', 'wp-cyber-security' )  => number_format_i18n( isset( $last['modified'] ) ? (int) $last['modified'] : 0 ),
			__( 'Deleted files', 'wp-cyber-security' )   => number_format_i18n( isset( $last['deleted'] ) ? (int) $last['deleted'] : 0 ),
			__( 'Threats', 'wp-cyber-security' )         => number_format_i18n( isset( $last['threats'] ) ? (int) $last['threats'] : 0 ),
			__( 'Quarantined', 'wp-cyber-security' )     => number_format_i18n( isset( $last['quarantined'] ) ? (int) $last['quarantined'] : 0 ),
			__( 'Skipped', 'wp-cyber-security' )         => number_format_i18n( isset( $last['skipped'] ) ? (int) $last['skipped'] : 0 ),
		);
		if ( isset( $last['missing_core'] ) && (int) $last['missing_core'] >= 0 ) {
			$rows[ __( 'Missing core files', 'wp-cyber-security' ) ] = number_format_i18n( (int) $last['missing_core'] );
		}
		if ( ! empty( $last['database'] ) ) {
			$rows[ __( 'Database findings', 'wp-cyber-security' ) ] = number_format_i18n( isset( $last['db_findings'] ) ? (int) $last['db_findings'] : 0 );
		}
		if ( isset( $last['new_admins'] ) ) {
			$rows[ __( 'New administrators found', 'wp-cyber-security' ) ] = number_format_i18n( (int) $last['new_admins'] );
		}
		$db = get_option( Db_Scanner::LAST_OPTION, array() );
		if ( is_array( $db ) && ! empty( $db['finished_at'] ) ) {
			$rows[ __( 'Last database scan', 'wp-cyber-security' ) ] = sprintf(
				/* translators: 1: date, 2: options, 3: posts, 4: findings */
				__( '%1$s: %2$s options and %3$s posts checked, %4$s suspicious values', 'wp-cyber-security' ),
				$this->when( (int) $db['finished_at'] ),
				number_format_i18n( isset( $db['options_total'] ) ? (int) $db['options_total'] : 0 ),
				number_format_i18n( isset( $db['posts_total'] ) ? (int) $db['posts_total'] : 0 ),
				number_format_i18n( isset( $db['findings'] ) ? (int) $db['findings'] : 0 )
			);
		}
		$rows[ __( 'Files monitored', 'wp-cyber-security' ) ] = number_format_i18n( (int) wpcybersec()->store->manifest_count() );
		if ( ! empty( $last['message'] ) ) {
			$rows[ __( 'Message', 'wp-cyber-security' ) ] = (string) $last['message'];
		}
		return $html . $this->kv( $rows ) . '</section>';
	}

	/**
	 * Every open item with its matches and a code excerpt.
	 *
	 * @return string
	 */
	private function section_items() {
		$store  = wpcybersec()->store;
		$result = $store->items_query(
			array(
				'status'   => Store::STATUS_PENDING,
				'orderby'  => 'severity',
				'order'    => 'DESC',
				'per_page' => self::MAX_ITEMS,
				'page'     => 1,
			)
		);
		$items = (array) $result['rows'];
		$total = (int) $result['total'];

		$html = '<section><h2>' . $this->t( __( 'Open items', 'wp-cyber-security' ) ) . ' <span class="count">' . esc_html( number_format_i18n( $total ) ) . '</span></h2>';
		if ( ! $items ) {
			return $html . '<p>' . $this->t( __( 'Nothing is waiting for a decision.', 'wp-cyber-security' ) ) . '</p></section>';
		}
		$html .= '<p class="muted">' . $this->t( __( 'Held uploads, plugin and theme installs, unknown or changed files, new administrator accounts and threats that wait for an administrator. Most serious first.', 'wp-cyber-security' ) ) . '</p>';
		if ( $total > count( $items ) ) {
			$html .= '<p class="note">' . $this->t(
				sprintf(
					/* translators: 1: listed, 2: total */
					__( 'The first %1$s of %2$s items are listed.', 'wp-cyber-security' ),
					number_format_i18n( count( $items ) ),
					number_format_i18n( $total )
				)
			) . '</p>';
		}

		$excerpts = 0;
		foreach ( $items as $item ) {
			$with = false;
			if ( in_array( $item['type'], array( Store::TYPE_FILE, Store::TYPE_THREAT ), true ) && ! Db_Scanner::is_db_item( $item ) && $excerpts < self::MAX_EXCERPTS ) {
				$with = true;
				++$excerpts;
			}
			$html .= $this->item_html( $item, $with, $excerpts <= self::MAX_NETWORK );
		}
		if ( $excerpts >= self::MAX_EXCERPTS ) {
			$html .= '<p class="note">' . $this->t(
				sprintf(
					/* translators: %s: number */
					__( 'Code excerpts are included for the first %s files only.', 'wp-cyber-security' ),
					number_format_i18n( self::MAX_EXCERPTS )
				)
			) . '</p>';
		}
		return $html . '</section>';
	}

	/**
	 * @param array $item    Item.
	 * @param bool  $excerpt Include a code excerpt.
	 * @param bool  $network Allow downloading the official original.
	 * @return string
	 */
	private function item_html( array $item, $excerpt, $network ) {
		$details = isset( $item['details'] ) && is_array( $item['details'] ) ? $item['details'] : array();
		$types   = array(
			Store::TYPE_UPLOAD  => __( 'Upload', 'wp-cyber-security' ),
			Store::TYPE_INSTALL => __( 'Install', 'wp-cyber-security' ),
			Store::TYPE_FILE    => __( 'File', 'wp-cyber-security' ),
			Store::TYPE_THREAT  => __( 'Threat', 'wp-cyber-security' ),
			Store::TYPE_USER    => __( 'New administrator', 'wp-cyber-security' ),
		);
		$type    = isset( $types[ $item['type'] ] ) ? $types[ $item['type'] ] : (string) $item['type'];
		if ( Db_Scanner::is_db_item( $item ) ) {
			$type = __( 'Database', 'wp-cyber-security' );
		}
		$sev = max( 0, min( 3, (int) $item['severity'] ) );

		if ( Store::TYPE_USER === $item['type'] ) {
			$name = User_Watch::item_login( $item ) . ' (#' . User_Watch::item_user_id( $item ) . ')';
		} elseif ( Db_Scanner::is_db_item( $item ) ) {
			$name = Db_Scanner::location_label( $item );
		} elseif ( Store::TYPE_INSTALL === $item['type'] ) {
			$name = ! empty( $details['name'] ) ? (string) $details['name'] : (string) $item['path'];
		} else {
			$name = (string) $item['path'];
		}

		$html  = '<article class="item sev-' . $sev . '"><div class="item-head"><span class="badge type">' . $this->t( $type ) . '</span> ';
		$html .= '<span class="badge sev sev-' . $sev . '">' . $this->t( Store::severity_label( $sev ) ) . '</span> ';
		$html .= '<code class="path">' . $this->t( $name ) . '</code></div>';

		$rows = array(
			__( 'Item', 'wp-cyber-security' )     => '#' . (int) $item['id'],
			__( 'Detected', 'wp-cyber-security' ) => $this->when( (int) strtotime( (string) $item['created_at'] . ' UTC' ) ),
		);
		if ( Store::TYPE_USER === $item['type'] ) {
			if ( ! empty( $details['user_email'] ) ) {
				$rows[ __( 'Email', 'wp-cyber-security' ) ] = self::mask_email( (string) $details['user_email'] );
			}
			if ( ! empty( $details['user_registered'] ) ) {
				$rows[ __( 'Registered', 'wp-cyber-security' ) ] = (string) $details['user_registered'] . ' UTC';
			}
			if ( ! empty( $details['roles'] ) && is_array( $details['roles'] ) ) {
				$rows[ __( 'Roles', 'wp-cyber-security' ) ] = implode( ', ', array_map( 'strval', $details['roles'] ) );
			}
		}
		if ( Store::TYPE_INSTALL === $item['type'] ) {
			foreach ( array( 'version' => __( 'Version', 'wp-cyber-security' ), 'slug' => __( 'Folder', 'wp-cyber-security' ), 'install_source' => __( 'Installed from', 'wp-cyber-security' ) ) as $key => $label ) {
				if ( ! empty( $details[ $key ] ) ) {
					$rows[ $label ] = (string) $details[ $key ];
				}
			}
		}
		if ( Store::TYPE_UPLOAD === $item['type'] && ! empty( $item['source'] ) ) {
			$rows[ __( 'Received through', 'wp-cyber-security' ) ] = (string) $item['source'];
		}
		if ( ! empty( $details['change'] ) && Store::TYPE_USER !== $item['type'] ) {
			$rows[ __( 'Change', 'wp-cyber-security' ) ] = 'modified' === $details['change'] ? __( 'Modified file', 'wp-cyber-security' ) : __( 'New file', 'wp-cyber-security' );
		}
		if ( isset( $details['checksum'] ) && 'mismatch' === $details['checksum'] ) {
			$rows[ __( 'Official checksum', 'wp-cyber-security' ) ] = __( 'Differs from the official file', 'wp-cyber-security' );
		}
		if ( (int) $item['size'] > 0 ) {
			$rows[ __( 'Size', 'wp-cyber-security' ) ] = size_format( (int) $item['size'], 1 );
		}
		if ( '' !== (string) $item['sha256'] && ! Db_Scanner::is_db_item( $item ) ) {
			$rows['SHA-256'] = (string) $item['sha256'];
		}
		if ( '' !== (string) $item['quarantine_path'] ) {
			$rows[ __( 'Held copy', 'wp-cyber-security' ) ] = __( 'Yes, in quarantine', 'wp-cyber-security' );
		}
		if ( 'review' === (string) $item['source'] ) {
			$rows[ __( 'Reported', 'wp-cyber-security' ) ] = __( 'By an administrator from Recent changes', 'wp-cyber-security' );
		}
		$html .= $this->kv( $rows );

		$hits = isset( $details['hits'] ) && is_array( $details['hits'] ) ? $details['hits'] : array();
		if ( $hits ) {
			$html .= '<h3>' . $this->t(
				sprintf(
					/* translators: %s: number of matches */
					_n( '%s malware signature match', '%s malware signature matches', count( $hits ), 'wp-cyber-security' ),
					number_format_i18n( count( $hits ) )
				)
			) . '</h3><ol class="hits">';
			$base = basename( (string) $item['path'] );
			foreach ( array_slice( $hits, 0, 25 ) as $hit ) {
				if ( ! is_array( $hit ) ) {
					continue;
				}
				$title   = ! empty( $hit['title'] ) ? (string) $hit['title'] : __( 'Suspicious code', 'wp-cyber-security' );
				$snippet = isset( $hit['snippet'] ) ? Diff::redact_snippet( (string) $hit['snippet'], ! empty( $hit['file'] ) ? basename( (string) $hit['file'] ) : $base ) : '';
				if ( strlen( $snippet ) > 400 ) {
					$snippet = ( function_exists( 'mb_strcut' ) ? mb_strcut( $snippet, 0, 400, 'UTF-8' ) : substr( $snippet, 0, 400 ) ) . ' ...';
				}
				$html .= '<li><span class="badge sev sev-' . max( 0, min( 3, isset( $hit['severity'] ) ? (int) $hit['severity'] : 0 ) ) . '">' . $this->t( Store::severity_label( isset( $hit['severity'] ) ? (int) $hit['severity'] : 0 ) ) . '</span> <strong>' . $this->t( $title ) . '</strong>';
				if ( ! empty( $hit['file'] ) ) {
					$html .= ' <code>' . $this->t( (string) $hit['file'] ) . '</code>';
				}
				if ( ! empty( $hit['line'] ) ) {
					/* translators: %s: line number */
					$html .= ' <span class="muted">' . $this->t( sprintf( __( 'line %s', 'wp-cyber-security' ), number_format_i18n( (int) $hit['line'] ) ) ) . '</span>';
				}
				if ( ! empty( $hit['sig'] ) ) {
					$html .= ' <code class="muted">' . $this->t( (string) $hit['sig'] ) . '</code>';
				}
				if ( '' !== $snippet ) {
					$html .= '<pre>' . $this->t( $snippet ) . '</pre>';
				}
				$html .= '</li>';
			}
			$html .= '</ol>';
			if ( count( $hits ) > 25 ) {
				$html .= '<p class="muted">' . $this->t(
					sprintf(
						/* translators: %s: number */
						__( '%s more matches are not listed.', 'wp-cyber-security' ),
						number_format_i18n( count( $hits ) - 25 )
					)
				) . '</p>';
			}
		}

		if ( $excerpt ) {
			$html .= $this->excerpt_html( $item, $network );
		}
		return $html . '</article>';
	}

	/**
	 * @param array $item    Item.
	 * @param bool  $network Allow downloading the official original.
	 * @return string
	 */
	private function excerpt_html( array $item, $network ) {
		try {
			$ex = Diff::excerpt( $item, self::EXCERPT_LINES, $network );
		} catch ( \Throwable $e ) {
			return '<p class="note">' . $this->t( __( 'The code of this file could not be read for the report.', 'wp-cyber-security' ) ) . '</p>';
		}
		if ( 'diff' === $ex['mode'] ) {
			$head = sprintf(
				/* translators: 1: lines added, 2: lines removed, 3: what it is compared with, 4: current version */
				__( 'What changed: +%1$s -%2$s lines, %3$s compared with %4$s', 'wp-cyber-security' ),
				number_format_i18n( $ex['added'] ),
				number_format_i18n( $ex['removed'] ),
				$ex['base_label'],
				$ex['current_label']
			);
		} elseif ( 'content' === $ex['mode'] ) {
			$head = sprintf(
				/* translators: %s: which version, such as "Current file on the server" */
				__( 'Code excerpt (%s)', 'wp-cyber-security' ),
				$ex['current_label']
			);
		} else {
			return '<p class="note">' . $this->t( '' !== $ex['reason_text'] ? $ex['reason_text'] : __( 'There is no code to show for this item.', 'wp-cyber-security' ) ) . '</p>';
		}

		$html = '<h3>' . $this->t( $head ) . '</h3>';
		if ( 'content' === $ex['mode'] && '' !== $ex['reason_text'] ) {
			$html .= '<p class="muted">' . $this->t( $ex['reason_text'] ) . '</p>';
		}
		foreach ( $ex['notes'] as $note ) {
			$html .= '<p class="muted">' . $this->t( $note ) . '</p>';
		}
		$diff  = 'diff' === $ex['mode'];
		$html .= '<table class="code"><colgroup>' . ( $diff ? '<col class="n"><col class="n">' : '<col class="n">' ) . '<col></colgroup><tbody>';
		foreach ( $ex['rows'] as $row ) {
			if ( '@' === $row['kind'] ) {
				$html .= '<tr class="hunk"><td colspan="' . ( $diff ? 3 : 2 ) . '">...</td></tr>';
				continue;
			}
			$class = array(
				'+' => 'add',
				'-' => 'del',
				'!' => 'hit',
				' ' => '',
			);
			$html .= '<tr class="' . esc_attr( isset( $class[ $row['kind'] ] ) ? $class[ $row['kind'] ] : '' ) . '">';
			if ( $diff ) {
				$html .= '<td class="n">' . ( $row['old'] ? (int) $row['old'] : '' ) . '</td><td class="n">' . ( $row['new'] ? (int) $row['new'] : '' ) . '</td>';
				$sign  = '+' === $row['kind'] ? '+' : ( '-' === $row['kind'] ? '-' : ' ' );
			} else {
				$html .= '<td class="n">' . (int) $row['new'] . '</td>';
				$sign  = '';
			}
			$html .= '<td class="c">' . $this->t( $sign . $row['text'] ) . '</td></tr>';
		}
		$html .= '</tbody></table>';
		if ( $ex['truncated'] ) {
			$html .= '<p class="muted">' . $this->t(
				sprintf(
					/* translators: %s: number of lines */
					__( 'Shortened to %s lines. Open the file on the Reports page to see all of it.', 'wp-cyber-security' ),
					number_format_i18n( self::EXCERPT_LINES )
				)
			) . '</p>';
		}
		return $html;
	}

