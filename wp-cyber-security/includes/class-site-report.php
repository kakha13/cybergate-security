	/**
	 * Environment checks.
	 *
	 * @return string
	 */
	private function section_environment() {
		$checks = array();
		try {
			$checks = (array) wpcybersec()->sysadmin->diagnostics();
		} catch ( \Throwable $e ) {
			$checks = array();
		}
		$html = '<section><h2>' . $this->t( __( 'Environment checks', 'wp-cyber-security' ) ) . '</h2>';
		if ( ! $checks ) {
			return $html . '<p>' . $this->t( __( 'The environment checks could not be run.', 'wp-cyber-security' ) ) . '</p></section>';
		}
		$labels = array(
			'pass' => __( 'OK', 'wp-cyber-security' ),
			'warn' => __( 'Warning', 'wp-cyber-security' ),
			'fail' => __( 'Problem', 'wp-cyber-security' ),
			'info' => __( 'Info', 'wp-cyber-security' ),
		);
		$html .= '<table class="list"><thead><tr><th>' . $this->t( __( 'Check', 'wp-cyber-security' ) ) . '</th><th>' . $this->t( __( 'Result', 'wp-cyber-security' ) ) . '</th><th>' . $this->t( __( 'Details', 'wp-cyber-security' ) ) . '</th></tr></thead><tbody>';
		foreach ( $checks as $check ) {
			if ( ! is_array( $check ) ) {
				continue;
			}
			$status = isset( $check['status'] ) ? (string) $check['status'] : 'info';
			$detail = isset( $check['detail'] ) ? wp_strip_all_tags( (string) $check['detail'] ) : '';
			$fix    = isset( $check['fix'] ) && is_string( $check['fix'] ) ? wp_strip_all_tags( $check['fix'] ) : '';
			$html  .= '<tr><td>' . $this->t( isset( $check['label'] ) ? (string) $check['label'] : '' ) . '</td><td><span class="st st-' . esc_attr( $status ) . '">' . $this->t( isset( $labels[ $status ] ) ? $labels[ $status ] : $status ) . '</span></td><td>' . $this->t( $detail );
			if ( '' !== $fix && 'pass' !== $status ) {
				$html .= '<div class="muted">' . $this->t( $fix ) . '</div>';
			}
			$html .= '</td></tr>';
		}
		return $html . '</tbody></table></section>';
	}

