<?php
/**
 * Reads and writes the early guard's config file.
 *
 * @package WPCyberSecurity
 */

namespace WPCyberSecurity;

defined( 'ABSPATH' ) || exit;

/**
 * The guard (guard/guard.php) runs through auto_prepend_file before WordPress
 * loads, so it cannot read options. It reads <data>/guard/config.php instead:
 *
 *   return array(
 *     'enabled'        => true,
 *     'action'         => 'block',            // block | strip
 *     'quarantine_dir' => '/abs/data/quarantine/guard',
 *     'spool_file'     => '/abs/data/spool/guard-uploads.jsonl',
 *     'allow_file'     => '/abs/data/guard/allow.php', // returns array( sha256 => 1 )
 *     'exempt'         => array( '/wp-admin/async-upload.php', ... ),
 *     'max_bytes'      => 104857600,
 *     'message'        => 'Upload held for administrator approval.',
 *   );
 *
 * Works without the plugin being booted (used by the deactivation hook).
 */
class Guard_Config {

	/**
	 * @return string
	 */
	public static function file() {
		return ( new Storage() )->guard_dir() . '/config.php';
	}

	/**
	 * @return string
	 */
	public static function allow_file() {
		return ( new Storage() )->guard_dir() . '/allow.php';
	}

	/**
	 * @return array Empty array when no config exists.
	 */
	public static function read() {
		$file = self::file();
		if ( ! is_readable( $file ) ) {
			return array();
		}
		$config = include $file;
		return is_array( $config ) ? $config : array();
	}

	/**
	 * @param array $config Full config array.
	 * @return bool
	 */
	public static function write( array $config ) {
		$storage = new Storage();
		$storage->ensure();
		$code = "<?php\n// Generated by CyberGate Security. Edit the settings page instead.\nreturn " . var_export( $config, true ) . ";\n"; // phpcs:ignore WordPress.PHP.DevelopmentFunctions
		return self::atomic_write( self::file(), $code );
	}

	/**
	 * Flips the enabled flag without touching the rest.
	 *
	 * @param bool $enabled New state.
	 */
	public static function set_enabled( $enabled ) {
		$config = self::read();
		if ( ! $config ) {
			return;
		}
		$config['enabled'] = (bool) $enabled;
		self::write( $config );
	}

	/**
	 * Writes a file through a temp file + rename so the guard never reads half a file.
	 *
	 * @param string $file    Target.
	 * @param string $content Content.
	 * @return bool
	 */
	public static function atomic_write( $file, $content ) {
		$tmp = $file . '.' . uniqid( 'tmp', true );
		// phpcs:ignore WordPress.WP.AlternativeFunctions.file_system_operations_file_put_contents
		if ( false === @file_put_contents( $tmp, $content, LOCK_EX ) ) {
			return false;
		}
		Fs::chmod( $tmp, 0640 );
		if ( ! Fs::replace( $tmp, $file ) ) {
			Fs::delete( $tmp );
			return false;
		}
		if ( function_exists( 'opcache_invalidate' ) ) {
			@opcache_invalidate( $file, true ); // phpcs:ignore WordPress.PHP.NoSilencedErrors
		}
		return true;
	}
}
